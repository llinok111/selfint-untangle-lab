// Assertions against the analytic box oracle. Exit 0 only if every gate passes.
import { readFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { parseMesh, analyze, repair, vertexVolume, containsPoint, checkWitness } from "../src/core.mjs";

const fail = [];
const assert = (cond, msg) => { if (!cond) fail.push(msg); };
const sha = (p) => createHash("sha256").update(readFileSync(p)).digest("hex");
const before = sha("data/corpus.json");
execFileSync(process.execPath, ["tools/gen-sample.mjs"], { stdio: "ignore" });
const after = sha("data/corpus.json");
assert(before === after, `gen-sample not deterministic: ${before} != ${after}`);
console.log(`G7 corpus regenerated byte-identical sha256=${after.slice(0, 16)}…`);

const data = JSON.parse(readFileSync("data/corpus.json", "utf8"));
const W = BigInt(data.box.W), H = BigInt(data.box.H), T = BigInt(data.box.T);
const boxVolume6 = W * H * T * 6n;
const cell = W / BigInt(data.grid);

let cases = 0, defectsBefore = 0, actions = 0, repaired = 0, exactVolume = 0, watertight = 0;
let witnesses = 0, witnessesOk = 0, points = 0, misses = 0, ambiguous = 0;
const defectByClass = {};

for (const c of data.cases) {
  cases++;
  const mesh = parseMesh(c.mesh);
  const a = analyze(mesh);
  defectsBefore += a.stats.defects;
  defectByClass[c.class] = (defectByClass[c.class] || 0) + a.stats.defects;
  assert(a.stats.defects > 0, `${c.id}: injection produced no defect`);
  for (const p of a.pairs) if (p.kind === "crossing") { witnesses++; if (checkWitness(mesh, p)) witnessesOk++; }

  const r = repair(mesh);
  actions += r.actions.length;
  if (r.defects === 0) repaired++;
  if (r.topology.boundary === 0 && r.topology.nonManifold === 0 && r.topology.reversed === 0) watertight++;
  if (r.volume[0] === boxVolume6 && r.volume[1] === 6n) exactVolume++;
  assert(r.defects === 0, `${c.id}: ${r.defects} defects remain`);
  assert(r.topology.boundary === 0 && r.topology.nonManifold === 0, `${c.id}: not watertight ${JSON.stringify(r.topology)}`);
  assert(r.volume[0] === boxVolume6 && r.volume[1] === 6n, `${c.id}: volume ${r.volume} != ${boxVolume6}`);

  // stratified containment: 600 uniform interior + 400 points in the spike column
  let seed = 12345 + c.id.length * 977;
  const rnd = () => (seed = (seed * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff;
  const pts = [];
  for (let i = 0; i < 600; i++) {
    pts.push([BigInt(Math.floor((0.02 + 0.96 * rnd()) * Number(W))),
              BigInt(Math.floor((0.02 + 0.96 * rnd()) * Number(H))),
              BigInt(Math.floor((0.02 + 0.96 * rnd()) * Number(T)))]);
  }
  const sx = BigInt(c.spikes[0].injected[0]), sy = BigInt(c.spikes[0].injected[1]);
  for (let i = 0; i < 400; i++) {
    pts.push([sx + BigInt(Math.floor((rnd() - 0.5) * 0.9 * Number(cell))),
              sy + BigInt(Math.floor((rnd() - 0.5) * 0.9 * Number(cell))),
              BigInt(Math.floor((0.05 + 0.9 * rnd()) * Number(T)))]);
  }
  for (const p of pts) {
    points++;
    const q = containsPoint(r.mesh, p);
    if (!q.agree) { ambiguous++; continue; }
    if (!q.inside) misses++;
  }
}

// scale invariance: repair must be identical at 1e1, 1e2, 1e3
let scaleOk = 0;
for (const c of data.cases.filter((_, i) => i % 6 === 0)) {
  const base = analyze(parseMesh(c.mesh)).stats.defects;
  for (const k of [1n, 2n, 3n]) {
    const f = 10n ** k;
    const scaled = { vertices: c.mesh.vertices.map((v) => v.map((x) => (BigInt(x) * f).toString())), triangles: c.mesh.triangles };
    const r = repair(parseMesh(scaled));
    const ok = r.defects === 0 && r.volume[0] === boxVolume6 * f ** 3n && r.volume[1] === 6n && analyze(parseMesh(scaled)).stats.defects === base;
    if (ok) scaleOk++;
    assert(ok, `${c.id}: scale 10^${k} broke repair/volume/count`);
  }
}

// baseline: detection-only leaves every case defective
const baseline = JSON.parse(execFileSync(process.execPath, ["baseline/detect-only.mjs"], { encoding: "utf8" }));

console.log(`G4 cases=${cases} defectsBefore=${defectsBefore} actions=${actions} repaired=${repaired}/${cases} watertight=${watertight}/${cases} exactVolume=${exactVolume}/${cases}`);
console.log(`G4 witnesses=${witnessesOk}/${witnesses} containment=${points - misses}/${points} misses=${misses} ambiguous=${ambiguous}`);
console.log(`G4 scaleInvariant=${scaleOk}/30  defectsByClass=${JSON.stringify(defectByClass)}`);
console.log(`G1 baseline(detection-only) defectiveCases=${baseline.defectiveCases}/${cases} remainingDefects=${baseline.remainingDefects}`);

assert(repaired === cases, `repair ${repaired}/${cases}`);
assert(watertight === cases, `watertight ${watertight}/${cases}`);
assert(exactVolume === cases, `volume ${exactVolume}/${cases}`);
assert(witnessesOk === witnesses && witnesses > 0, `witnesses ${witnessesOk}/${witnesses}`);
assert(misses === 0 && ambiguous === 0, `containment misses=${misses} ambiguous=${ambiguous}`);
assert(scaleOk === 30, `scale ${scaleOk}/30`);
assert(baseline.defectiveCases === cases, `baseline defective ${baseline.defectiveCases}/${cases}`);

if (fail.length) { console.error("FAIL\n" + fail.join("\n")); process.exit(1); }
console.log("PASS all assertions (60 cases, exact volume, 60k containment points, 30 scale runs)");
